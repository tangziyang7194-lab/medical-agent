def get_provinces() -> list:
    """获取省份列表"""
    return list(PROVINCES)


def get_cities(province: str) -> list:
    """获取某省份的城市列表"""
    return CITIES.get(province, [])


def get_districts(city_or_district: str) -> list:
    """获取某城市的区县列表，若为直辖市的区则返回街道/镇"""
    return DISTRICTS.get(city_or_district, [])


def is_municipality(province: str) -> bool:
    """判断是否为直辖市"""
    return province in ["北京市", "天津市", "上海市", "重庆市"]


def format_location(province: str, city: str, district: str) -> str:
    """格式化完整地址"""
    if is_municipality(province):
        return f"{province}{city}{district}" if district else f"{province}{city}"
    return f"{province}{city}{district}" if district else f"{province}{city}"
